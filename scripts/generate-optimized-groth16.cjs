function step(index, digit, preparedIndex) {
    const lines = []
    lines.push(`        // Miller digit ${index}: ${digit}`)
    lines.push('        acc = BN256.squareFQ12(acc)')
    if (digit === 1) {
        lines.push('        acc = BN256.mulFQ12(acc, initialAccumulator)')
    } else if (digit === -1) {
        lines.push('        acc = BN256.mulFQ12(acc, inverseAccumulator)')
    }
    lines.push('        line0 = BN256Pairing.lineFuncDouble(r0, p0)')
    lines.push('        acc = BN256Pairing.mulLine(acc, line0.a, line0.b, line0.c)')
    lines.push('        acc = BN256.modFQ12(acc)')
    lines.push(`        acc = OptimizedG16BN256.mulPreparedLine(acc, gammaLines[${preparedIndex}], p1)`)
    lines.push(`        acc = OptimizedG16BN256.mulPreparedLine(acc, deltaLines[${preparedIndex}], p2)`)
    lines.push('        r0 = BN256.modTwistPoint(line0.rOut)')
    if (digit !== 0) {
        const suffix = digit === 1 ? '' : 'Minus'
        lines.push(`        line0 = BN256Pairing.lineFuncAdd(r0, q0${suffix}, p0, addR20)`)
        lines.push('        acc = BN256Pairing.mulLine(acc, line0.a, line0.b, line0.c)')
        lines.push('        acc = BN256.modFQ12(acc)')
        lines.push(`        acc = OptimizedG16BN256.mulPreparedLine(acc, gammaLines[${preparedIndex + 1}], p1)`)
        lines.push(`        acc = OptimizedG16BN256.mulPreparedLine(acc, deltaLines[${preparedIndex + 1}], p2)`)
        lines.push('        r0 = BN256.modTwistPoint(line0.rOut)')
    }
    return lines.join('\n')
}

let preparedIndex = 0
const body = digits.map((digit, index) => {
    const rendered = step(index, digit, preparedIndex)
    preparedIndex += digit === 0 ? 1 : 2
    return rendered
}).join('\n\n')
